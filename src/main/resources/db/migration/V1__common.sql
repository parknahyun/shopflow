-- V1: 공통 테이블(멱등키, 변경 이력)
-- 열거형은 데이터베이스 열거형 타입 대신 문자열과 검사 제약으로 둔다(값을 바꿀 때 ALTER TYPE이 필요 없고
-- 객체 매핑 검증이 단순하다). 이후 마이그레이션도 같은 방식을 따른다.

CREATE TABLE idempotency_key (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope            VARCHAR(30)  NOT NULL,
    idem_key         VARCHAR(100) NOT NULL,
    request_hash     VARCHAR(64)  NOT NULL,
    status           VARCHAR(20)  NOT NULL,
    result           JSONB,
    claim_expires_at TIMESTAMPTZ,
    expires_at       TIMESTAMPTZ  NOT NULL,
    created_at       TIMESTAMPTZ  NOT NULL,
    CONSTRAINT ck_idempotency_status CHECK (status IN ('PROCESSING', 'COMPLETED', 'FAILED')),
    CONSTRAINT uq_idempotency_scope_key UNIQUE (scope, idem_key)
);

CREATE INDEX ix_idempotency_expires_at ON idempotency_key (expires_at);
-- 점유 시간이 지난 처리 중 키를 찾는다.
CREATE INDEX ix_idempotency_claim ON idempotency_key (status, claim_expires_at);

COMMENT ON TABLE idempotency_key IS '중복 방지. (범위, 키)가 유일하다. 키는 시도마다 새로 만든다. 오래된 키는 정리 작업이 지운다.';
COMMENT ON COLUMN idempotency_key.scope IS '결제 시작, 결제 승인, 취소, 환불, 웹훅';
COMMENT ON COLUMN idempotency_key.idem_key IS '웹훅은 대행사 이벤트 식별자를 쓴다';
COMMENT ON COLUMN idempotency_key.request_hash IS '요청 내용 해시. 같은 키에 다른 내용이면 거절';
COMMENT ON COLUMN idempotency_key.result IS '저장된 처리 결과. 실패한 결과도 저장한다';
COMMENT ON COLUMN idempotency_key.claim_expires_at IS '처리 중 점유 만료 시각. 지나면 다른 요청이 대행사 조회로 이어받거나 실패로 바꾼다';
COMMENT ON COLUMN idempotency_key.expires_at IS '끝난 키를 정리하는 시각';

CREATE TABLE audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_type VARCHAR(30)  NOT NULL,
    target_id   BIGINT       NOT NULL,
    from_status VARCHAR(30),
    to_status   VARCHAR(30)  NOT NULL,
    actor       VARCHAR(100) NOT NULL,
    occurred_at TIMESTAMPTZ  NOT NULL
);

CREATE INDEX ix_audit_log_target ON audit_log (target_type, target_id);

COMMENT ON TABLE audit_log IS '변경 이력. 추가만 하고 수정과 삭제를 하지 않는다. 개인정보, 카드 정보, 환불 계좌번호는 담지 않는다.';
COMMENT ON COLUMN audit_log.target_type IS '결제, 주문, 하위 주문, 재고 확보, 환불';
COMMENT ON COLUMN audit_log.target_id IS '식별자 참조(대상 종류에 따라 다름, 외래키 아님)';
COMMENT ON COLUMN audit_log.actor IS '행위자(계정 식별자 또는 시스템)';

-- 변경 이력은 데이터베이스가 수정과 삭제를 막는다.
CREATE FUNCTION audit_log_immutable() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION '변경 이력은 수정하거나 지울 수 없습니다.';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_audit_log_immutable
    BEFORE UPDATE OR DELETE ON audit_log
    FOR EACH ROW EXECUTE FUNCTION audit_log_immutable();
